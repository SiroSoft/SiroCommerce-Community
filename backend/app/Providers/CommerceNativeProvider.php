final class CommerceNativeProvider
{
    public function register(?App $app = null): void
    {
        $c = Container::getInstance();
        $c->singleton(CatalogAdminAdapter::class);
        $c->singleton(CatalogAdminPort::class, fn (Container $c): object => $c->make(CatalogAdminAdapter::class));
        $c->singleton(CatalogTaxonomyPort::class, fn (Container $c): object => $c->make(CatalogAdminAdapter::class));
        $c->singleton(CatalogCompletenessPort::class, fn (Container $c): object => $c->make(CatalogAdminAdapter::class));
        $c->singleton(CatalogImportStoreAdapter::class);
        $c->singleton(CatalogImportStore::class, fn (Container $c): object => $c->make(CatalogImportStoreAdapter::class));
        $c->singleton(InventoryAdminAdapter::class);
        $c->singleton(InventoryAdminPort::class, fn (Container $c): object => $c->make(InventoryAdminAdapter::class));
        $c->singleton(InventoryAdminService::class);
        $c->singleton(CatalogAdminService::class);
        $c->singleton(CatalogTaxonomyService::class);
        $c->singleton(CatalogCompletenessService::class);
        $c->singleton(CatalogTaxonomyService::class);
        $c->singleton(PromotionStoreAdapter::class);
        $c->singleton(PromotionReader::class, fn (Container $c): object => $c->make(PromotionStoreAdapter::class));
         $c->singleton(PromotionUsageWriter::class, fn (Container $c): object => $c->make(PromotionStoreAdapter::class));
         $c->singleton(PromotionDecisionAuditAdapter::class);
         $c->singleton(PromotionDecisionAudit::class, fn (Container $c): object => $c->make(PromotionDecisionAuditAdapter::class));
         $c->singleton(PromotionService::class);
         $c->singleton(\App\Modules\Promotion\Application\PromotionRuleService::class);
        $c->singleton(CouponStoreAdapter::class);
        $c->singleton(CouponStore::class, fn (Container $c): object => $c->make(CouponStoreAdapter::class));
        $c->singleton(CouponService::class);
        $c->singleton(UserStoreAdapter::class);
        $c->singleton(UserStore::class, fn (Container $c): object => $c->make(UserStoreAdapter::class));
        $c->singleton(AuthService::class);
        $c->singleton(DevRuntimeAdapter::class);
        $c->singleton(DevOperations::class, fn (Container $c): object => $c->make(DevRuntimeAdapter::class));
        $c->singleton(DevService::class);
        $c->singleton(AnalyticsStoreAdapter::class);
        $c->singleton(AnalyticsStore::class, fn (Container $c): object => $c->make(AnalyticsStoreAdapter::class));
        $c->singleton(AnalyticsReader::class, fn (Container $c): object => $c->make(AnalyticsStoreAdapter::class));
        $c->singleton(AnalyticsExporter::class, fn (Container $c): object => $c->make(AnalyticsStoreAdapter::class));
         $c->singleton(AnalyticsService::class);
         $c->singleton(BiExportService::class);
        $c->singleton(SeoStoreAdapter::class);
        $c->singleton(SeoStore::class, fn (Container $c): object => $c->make(SeoStoreAdapter::class));
        $c->singleton(SeoService::class);
        $c->singleton(SmartReadStoreAdapter::class);
        $c->singleton(SmartReadStore::class, fn (Container $c): object => $c->make(SmartReadStoreAdapter::class));
         $c->singleton(SearchIndex::class, fn (Container $c): object => $c->make(SmartReadStoreAdapter::class));
         $c->singleton(SearchTransport::class, HttpSearchTransport::class);
         $c->singleton(CatalogSearchProvider::class, function (): object {
             $provider = strtolower(trim((string) \Siro\Core\Env::get('CATALOG_SEARCH_PROVIDER', 'native')));
             $url = trim((string) \Siro\Core\Env::get('SEARCH_URL', ''));
             $key = trim((string) \Siro\Core\Env::get('SEARCH_API_KEY', ''));
             if ($provider !== 'meili' || $url === '' || $key === '') return new NullCatalogSearchProvider();
             return new MeiliCatalogSearchProvider(null, $url, $key);
         });
          $c->singleton(SearchAdapter::class, function (Container $c): object {
               $provider = strtolower(trim((string) \Siro\Core\Env::get('SEARCH_PROVIDER', 'native')));
               if ($provider === 'native') return new NativeSearchAdapter();
               if (!in_array($provider, ['opensearch', 'elasticsearch', 'meilisearch'], true)) throw new \RuntimeException('Unsupported search provider');
                $transport = $c->make(SearchTransport::class);
               if (!$transport instanceof SearchTransport) throw new \RuntimeException('Search transport binding invalid');
               return new NativeSearchAdapter($transport);
         });
        $c->singleton(SearchService::class);
        $c->singleton(RescueService::class);
        $c->singleton(SmartOperations::class, fn (Container $c): object => $c->make(SmartService::class));
        $c->singleton(SmartService::class);
        $c->singleton(CustomerStoreAdapter::class);
        $c->singleton(CustomerStore::class, fn (Container $c): object => $c->make(CustomerStoreAdapter::class));
        $c->singleton(CustomerReader::class, fn (Container $c): object => $c->make(CustomerStoreAdapter::class));
        $c->singleton(CustomerService::class);
          $c->singleton(ReportingReadAdapter::class, function (Container $c): object {
              $search = $c->make(SearchAdapter::class);
              if (!$search instanceof SearchAdapter) throw new \RuntimeException('Search adapter binding invalid');
              return new ReportingReadAdapter($search);
          });
        $c->singleton(ReportingReader::class, fn (Container $c): object => $c->make(ReportingReadAdapter::class));
         $c->singleton(ReportingService::class);
         $c->singleton(DashboardBiRepository::class);
         $c->singleton(DashboardBiReader::class, fn (Container $c): object => $c->make(DashboardBiRepository::class));
         $c->singleton(DashboardBiService::class);
         $c->singleton(AiSuggestionGateway::class, static fn (): object => match (strtolower(trim((string) \Siro\Core\Env::get('AI_PROVIDER', 'unavailable')))) {
             'openai' => new OpenAiCompatibleGateway(),
             'ollama' => new OllamaGateway(),
             default => new UnavailableAiSuggestionGateway(),
         });
         $c->singleton(AiAuditWriter::class, DatabaseAiAuditWriter::class);
         $c->singleton(AiCostLedger::class, PersistentAiCostLedger::class);
         $c->singleton(AiSuggestionService::class);
         $c->singleton(AiCopilotService::class);
         $c->singleton(AssistantService::class);
         $c->singleton(HeadlessSchemaReader::class, NativeHeadlessSchemaReader::class);
        $c->singleton(PricingSnapshotStoreAdapter::class);
        $c->singleton(PricingSnapshotStore::class, fn (Container $c): object => $c->make(PricingSnapshotStoreAdapter::class));
        $c->singleton(PricingBreadthAdapter::class);
        $c->singleton(PriceResolver::class, fn (Container $c): object => $c->make(PricingBreadthAdapter::class));
        $c->singleton(CurrencyConverter::class, fn (Container $c): object => $c->make(PricingBreadthAdapter::class));
        $c->singleton(PricingService::class);
        $c->singleton(QuoteService::class);
         $c->singleton(ProductTypeService::class);
        $c->singleton(DigitalDeliveryStoreAdapter::class);
         $c->singleton(DigitalDeliveryStore::class, fn (Container $c): object => $c->make(DigitalDeliveryStoreAdapter::class));
         $c->singleton(DigitalDeliveryTransport::class, LocalDigitalDeliveryTransport::class);
         $c->singleton(DigitalDeliveryService::class);
        $c->singleton(DhlSandboxTransport::class);
         $c->singleton(DhlTransport::class, function (Container $c): object {
             $environment = strtolower((string) Env::get('APP_ENV', 'local'));
             $mode = strtolower((string) Env::get('DHL_MODE', $environment === 'production' ? 'api' : 'sandbox'));
             if ($environment === 'production' && $mode !== 'api') throw new \RuntimeException('Sandbox DHL transport is forbidden in production');
             if ($mode === 'sandbox') return $c->make(DhlSandboxTransport::class);
             return new DhlHttpTransport(
                 (string) Env::get('DHL_API_URL', ''),
                 (string) Env::get('DHL_API_KEY', ''),
                 (string) Env::get('DHL_API_SECRET', ''),
             );
         });
        $c->singleton(DhlCarrier::class);
        $c->singleton(GhnCarrier::class);
        $c->singleton(ViettelPostCarrier::class);
        $c->singleton(Carrier::class, fn (Container $c): object => $c->make(DhlCarrier::class));
        $c->singleton(RateProvider::class, fn (Container $c): object => $c->make(DhlCarrier::class));
        $c->singleton(ShippingEvidenceStoreAdapter::class);
        $c->singleton(ShippingEvidenceStore::class, fn (Container $c): object => $c->make(ShippingEvidenceStoreAdapter::class));
        $c->singleton(ShippingShipmentStoreAdapter::class);
        $c->singleton(ShippingShipmentStore::class, fn (Container $c): object => $c->make(ShippingShipmentStoreAdapter::class));
        $c->singleton(ConfiguredShippingProviderRegistry::class);
        $c->singleton(ShippingProviderRegistry::class, fn (Container $c): object => $c->make(ConfiguredShippingProviderRegistry::class));
        $c->singleton(ShippingService::class);
    }
}
