final class CommerceServiceProvider
{
    public function register(?App $app = null): void
    {
        $container = Container::getInstance();
        (new CommerceNativeProvider())->register($app);
        (new CommerceCheckoutProvider())->register($app);
        $container->singleton(V2SideEffectRepository::class);
        $container->singleton(StoreChannelAdapter::class);
        $container->singleton(StoreChannelStore::class, fn (Container $c): object => $c->make(StoreChannelAdapter::class));
        $container->singleton(StoreChannelService::class);
        $container->singleton(B2BAdapter::class);
        $container->singleton(B2BStore::class, fn (Container $c): object => $c->make(B2BAdapter::class));
        $container->singleton(B2BApprovalService::class);
         $container->singleton(B2BWorkflowStore::class, fn (Container $c): object => $c->make(B2BAdapter::class));
         $container->singleton(B2BQuoteStore::class, fn (Container $c): object => $c->make(B2BAdapter::class));
         $container->singleton(B2BWorkflowService::class);
          $container->singleton(B2BEnterpriseService::class);
           $container->singleton(B2BCommercialService::class);
           $container->singleton(B2BPurchaseOrderService::class);
        $container->singleton(ProductCatalogReader::class);
        $container->singleton(CatalogReader::class, fn (Container $c): object => $c->make(ProductCatalogReader::class));
        $container->singleton(CatalogService::class);
        $container->singleton(VendorPayoutService::class);
        $container->singleton(CommerceEventListeners::class);
        $listeners = $container->make(CommerceEventListeners::class);
        if (!$listeners instanceof CommerceEventListeners) throw new \RuntimeException('Commerce event listener binding invalid');
        $listeners->register();
        foreach ([PaymentOperationStore::class, WebhookEventStore::class, OutboxWriter::class, JobStore::class] as $port) {
            $container->singleton($port, fn (Container $c): object => $c->make(V2SideEffectRepository::class));
        }
        $container->singleton(PaymentReconciliationStore::class, fn (Container $c): object => $c->make(V2SideEffectRepository::class));
        $container->singleton(PaymentTransport::class, StreamPaymentTransport::class);
        $container->singleton(PaymentProviderRegistry::class);
        $container->singleton(PaymentProvider::class, fn (Container $c): object => $c->make(PaymentProviderRegistry::class));
        $container->singleton(CmsStoreAdapter::class);
        $container->singleton(CmsStore::class, fn (Container $c): object => $c->make(CmsStoreAdapter::class));
        $container->singleton(CmsService::class);
        $container->singleton(WishlistStoreAdapter::class);
        $container->singleton(WishlistStore::class, fn (Container $c): object => $c->make(WishlistStoreAdapter::class));
        $container->singleton(WishlistService::class);
        $container->singleton(ReviewStoreAdapter::class);
        $container->singleton(ReviewStore::class, fn (Container $c): object => $c->make(ReviewStoreAdapter::class));
        $container->singleton(ReviewService::class);
        $container->singleton(GraphQlParser::class);
        $container->singleton(CustomerOrderOwnerReaderAdapter::class);
        $container->singleton(OrderOwnerReader::class, fn (Container $c): object => $c->make(CustomerOrderOwnerReaderAdapter::class));
        $container->singleton(HeadlessQueryService::class);
        $container->singleton(HeadlessQueryReader::class, fn (Container $c): object => $c->make(HeadlessQueryService::class));
        $container->singleton(PaymentReconciliationProvider::class, function (Container $c): object {
            $provider = $c->make(PaymentProvider::class);
            if (!$provider instanceof PaymentReconciliationProvider) throw new \RuntimeException('Payment provider has no reconciliation capability');
            return $provider;
        });
        $container->singleton(PaymentReconciliationService::class);
        $container->singleton(TaxProvider::class, NativeTaxProvider::class);
        $container->singleton(RateProvider::class, DefaultRateProvider::class);
        $container->singleton(PaymentOperationService::class);
        $container->singleton(PaymentStoreAdapter::class);
         $container->singleton(PaymentStore::class, fn (Container $c): object => $c->make(PaymentStoreAdapter::class));
         $container->singleton(PaymentAuditWriter::class);
         $container->singleton(AuditWriter::class, fn (Container $c): object => $c->make(PaymentAuditWriter::class));
         $container->singleton(PaymentCommandService::class);
        $container->singleton(PricingEngine::class);
        $container->singleton(WebhookReceiver::class);
        $container->singleton(FulfillmentStoreAdapter::class);
        $container->singleton(FulfillmentStore::class, fn (Container $c): object => $c->make(FulfillmentStoreAdapter::class));
        $container->singleton(Carrier::class, DefaultCarrier::class);
        $container->singleton(FulfillmentManager::class);
        $container->singleton(FulfillmentService::class, fn (Container $c): object => $c->make(FulfillmentManager::class));
        $container->singleton(ReturnStoreAdapter::class);
        $container->singleton(ReturnStore::class, fn (Container $c): object => $c->make(ReturnStoreAdapter::class));
        $container->singleton(CarrierReturnLabelAdapter::class);
        $container->singleton(ReturnLabelProvider::class, fn (Container $c): object => $c->make(CarrierReturnLabelAdapter::class));
        $container->singleton(ReturnManager::class);
        $container->singleton(ReturnService::class, fn (Container $c): object => $c->make(ReturnManager::class));
        $container->singleton(InvoiceStoreAdapter::class);
        $container->singleton(InvoiceStore::class, fn (Container $c): object => $c->make(InvoiceStoreAdapter::class));
        $container->singleton(InvoiceManager::class);
        $container->singleton(InvoiceService::class, fn (Container $c): object => $c->make(InvoiceManager::class));
        $container->singleton(CreditMemoStoreAdapter::class);
        $container->singleton(CreditMemoStore::class, fn (Container $c): object => $c->make(CreditMemoStoreAdapter::class));
        $container->singleton(CreditMemoManager::class);
         $container->singleton(CreditMemoService::class, fn (Container $c): object => $c->make(CreditMemoManager::class));
         $container->singleton(FinancialDocumentQueryService::class);
         $container->singleton(AdminFinancialReconciliationService::class);
         $container->singleton(SubscriptionStoreAdapter::class);
         $container->singleton(SubscriptionStore::class, fn (Container $c): object => $c->make(SubscriptionStoreAdapter::class));
          $container->singleton(SubscriptionService::class);
          $container->singleton(AdminSubscriptionService::class);
         $container->singleton(CustomerPrivacyService::class);
         $container->singleton(PromotionAllocationService::class);
         $container->singleton(ConsentRecordRepository::class);
         $container->singleton(ConsentService::class);
         $container->singleton(WebhookProcessor::class, function (Container $c): object {
             $events = $c->make(WebhookEventStore::class); $payments = $c->make(PaymentStore::class); $invoices = $c->make(InvoiceStore::class);
             if (!$events instanceof WebhookEventStore || !$payments instanceof PaymentStore || !$invoices instanceof InvoiceStore) throw new \RuntimeException('Webhook finance bindings invalid');
              $subscriptions = $c->make(SubscriptionService::class);
              return new WebhookProcessor($events, $payments, $invoices, $subscriptions instanceof SubscriptionService ? $subscriptions : null);
         });
        $processor = $container->make(WebhookProcessor::class);
        if (!$processor instanceof WebhookProcessor) throw new \RuntimeException('Webhook processor binding invalid');
        $processor->register();
        // Enabled extensions boot last so all core contracts exist first.
        // Best effort: never breaks core boot (see ExtensionBoot).
        \App\Modules\Extension\Application\ExtensionBoot::boot();
    }
}
